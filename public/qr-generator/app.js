let activeType = 'url';
const qrCanvas = document.getElementById('qrCanvas');
const fgColor = document.getElementById('fgColor');
const bgColor = document.getElementById('bgColor');
const fgHex = document.getElementById('fgHex');
const bgHex = document.getElementById('bgHex');
const qrSize = document.getElementById('qrSize');
const qrEcc = document.getElementById('qrEcc');

function getPayload() {
  if (activeType === 'url') {
    return document.getElementById('qrUrlInput').value.trim() || 'https://kray-digital.pp.ua/';
  }
  if (activeType === 'text') {
    return document.getElementById('qrTextInput').value || 'KRAY DIGITAL';
  }
  if (activeType === 'wifi') {
    const ssid = document.getElementById('wifiSsid').value.trim() || 'WiFi';
    const pass = document.getElementById('wifiPass').value;
    const enc = document.getElementById('wifiEnc').value;
    const hidden = document.getElementById('wifiHidden').checked ? 'true' : 'false';
    return `WIFI:T:${enc};S:${ssid};P:${pass};H:${hidden};;`;
  }
  const kind = document.getElementById('contactKind').value;
  const val = document.getElementById('contactVal').value.trim() || '+380671234567';
  if (kind === 'tel') return `tel:${val.replace(/\s+/g, '')}`;
  if (kind === 'mailto') return `mailto:${val}`;
  return `https://t.me/${val.replace(/^@/, '')}`;
}

function renderQR() {
  if (!window.QRCode) return;
  const text = getPayload();
  fgHex.textContent = fgColor.value;
  bgHex.textContent = bgColor.value;
  window.QRCode.toCanvas(qrCanvas, text, {
    width: 320,
    margin: 2,
    errorCorrectionLevel: qrEcc.value,
    color: { dark: fgColor.value, light: bgColor.value }
  }).catch((e) => console.error('QR render error:', e));
}

document.getElementById('typeTabs').addEventListener('click', (e) => {
  const btn = e.target.closest('.tab-btn');
  if (!btn) return;
  activeType = btn.dataset.type;
  document.querySelectorAll('.tab-btn').forEach(b => {
    const active = b === btn;
    b.classList.toggle('active', active);
    b.setAttribute('aria-selected', String(active));
  });
  document.querySelectorAll('.input-pane').forEach(p => { p.hidden = p.id !== `pane-${activeType}`; });
  renderQR();
});

['qrUrlInput', 'qrTextInput', 'wifiSsid', 'wifiPass', 'wifiEnc', 'wifiHidden', 'contactKind', 'contactVal', 'fgColor', 'bgColor', 'qrSize', 'qrEcc']
  .forEach(id => {
    const el = document.getElementById(id);
    if (el) el.addEventListener('input', renderQR);
    if (el) el.addEventListener('change', renderQR);
  });

function triggerDownload(url, filename) {
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
}

document.getElementById('dlPngBtn').addEventListener('click', async () => {
  const size = parseInt(qrSize.value, 10) || 512;
  const dataUrl = await window.QRCode.toDataURL(getPayload(), {
    width: size,
    margin: 2,
    errorCorrectionLevel: qrEcc.value,
    color: { dark: fgColor.value, light: bgColor.value }
  });
  triggerDownload(dataUrl, `kray-qr-${size}px.png`);
});

document.getElementById('dlSvgBtn').addEventListener('click', async () => {
  const svg = await window.QRCode.toString(getPayload(), {
    type: 'svg',
    margin: 2,
    errorCorrectionLevel: qrEcc.value,
    color: { dark: fgColor.value, light: bgColor.value }
  });
  const blob = new Blob([svg], { type: 'image/svg+xml;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  triggerDownload(url, 'kray-qr.svg');
  setTimeout(() => URL.revokeObjectURL(url), 4000);
});

document.getElementById('copySvgBtn').addEventListener('click', async () => {
  const svg = await window.QRCode.toString(getPayload(), {
    type: 'svg',
    margin: 2,
    errorCorrectionLevel: qrEcc.value,
    color: { dark: fgColor.value, light: bgColor.value }
  });
  await navigator.clipboard.writeText(svg);
  const span = document.getElementById('i18nCopySvg');
  if (span) {
    span.textContent = T.copiedSvg;
    setTimeout(() => { span.textContent = T.copySvg; }, 2000);
  }
});

