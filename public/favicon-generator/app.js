const fileInput = document.getElementById('fileInput');

function handleImageFile(file) {
  if (!file || !file.type.startsWith('image/')) return;
  const url = URL.createObjectURL(file);
  const img = new Image();
  img.onload = () => {
    loadedImg = img;
    mode = 'image';
    renderAllPreviews();
    URL.revokeObjectURL(url);
  };
  img.src = url;
}

