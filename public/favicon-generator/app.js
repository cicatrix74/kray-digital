document.getElementById('downloadZipBtn').addEventListener('click', async () => {
  if (!window.JSZip) return;
  const zip = new window.JSZip();
  zip.file('favicon.ico', await buildIcoBlob());
  zip.file('favicon-16x16.png', await renderSizeBlob(16));
  zip.file('favicon-32x32.png', await renderSizeBlob(32));
  zip.file('apple-touch-icon.png', await renderSizeBlob(180));
  zip.file('android-chrome-192x192.png', await renderSizeBlob(192));
  zip.file('android-chrome-512x512.png', await renderSizeBlob(512));
  zip.file('site.webmanifest', JSON.stringify({
    name: 'KRAY DIGITAL App',
    short_name: 'App',
    icons: [
      { src: '/android-chrome-192x192.png', sizes: '192x192', type: 'image/png' },
      { src: '/android-chrome-512x512.png', sizes: '512x512', type: 'image/png' }
    ],
    theme_color: favBgColor.value,
    background_color: favBgColor.value,
    display: 'standalone'
  }, null, 2));

  const zipBlob = await zip.generateAsync({ type: 'blob' });
  triggerDownload(zipBlob, 'favicon-package.zip');
});

