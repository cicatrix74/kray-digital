function drawIconToCanvas(canvas) {
  const size = canvas.width;
  const ctx = canvas.getContext('2d');
  ctx.clearRect(0, 0, size, size);

  const radiusPx = (parseInt(radiusSlider.value, 10) / 100) * size;

  ctx.save();
  ctx.beginPath();
  ctx.roundRect(0, 0, size, size, radiusPx);
  ctx.clip();

  if (!transparentBg.checked) {
    ctx.fillStyle = favBgColor.value;
    ctx.fillRect(0, 0, size, size);
  }

  if (mode === 'image' && loadedImg) {
    const ratio = Math.min(size / loadedImg.width, size / loadedImg.height);
    const w = loadedImg.width * ratio;
    const h = loadedImg.height * ratio;
    ctx.drawImage(loadedImg, (size - w) / 2, (size - h) / 2, w, h);
  } else {
    const txt = (favText.value || 'KD').trim();
    ctx.fillStyle = favTextColor.value;
    const fontScale = txt.length <= 1 ? 0.58 : txt.length === 2 ? 0.44 : 0.34;
    ctx.font = `700 ${Math.round(size * fontScale)}px "Space Grotesk", "Inter", sans-serif`;
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';
    ctx.fillText(txt, size / 2, size / 2 + size * 0.03);
  }

  ctx.restore();
}

function renderAllPreviews() {
  textHex.textContent = favTextColor.value;
  bgHex.textContent = favBgColor.value;
  radiusVal.textContent = `${radiusSlider.value}%`;
  ['preview16', 'preview32', 'preview48', 'preview180'].forEach((id) => {
    const c = document.getElementById(id);
    if (c) drawIconToCanvas(c);
  });
}

function renderSizeBlob(size) {
  const c = document.createElement('canvas');
  c.width = size;
  c.height = size;
  drawIconToCanvas(c);
  return new Promise((resolve) => c.toBlob(resolve, 'image/png'));
}

// Build multi-size binary .ico (PNG-encoded entries for 16, 32, 48px)
async function buildIcoBlob() {
  const sizes = [16, 32, 48];
  const pngBuffers = [];
  for (const s of sizes) {
    const blob = await renderSizeBlob(s);
    pngBuffers.push(new Uint8Array(await blob.arrayBuffer()));
  }

  const headerSize = 6 + sizes.length * 16;
  const totalBytes = headerSize + pngBuffers.reduce((sum, b) => sum + b.length, 0);
  const out = new Uint8Array(totalBytes);
  const view = new DataView(out.buffer);

  view.setUint16(0, 0, true); // reserved
  view.setUint16(2, 1, true); // type = 1 (ICO)
  view.setUint16(4, sizes.length, true);

  let offset = headerSize;
  sizes.forEach((s, idx) => {
    const entryOffset = 6 + idx * 16;
    const png = pngBuffers[idx];
    out[entryOffset + 0] = s;
    out[entryOffset + 1] = s;
    out[entryOffset + 2] = 0;
    out[entryOffset + 3] = 0;
    view.setUint16(entryOffset + 4, 1, true); // color planes
    view.setUint16(entryOffset + 6, 32, true); // bits per pixel
    view.setUint32(entryOffset + 8, png.length, true);
    view.setUint32(entryOffset + 12, offset, true);
    out.set(png, offset);
    offset += png.length;
  });

  return new Blob([out], { type: 'image/x-icon' });
}

function triggerDownload(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

