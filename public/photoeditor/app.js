  // Fallback hide loader if iframe load event is delayed
  setTimeout(() => editorLoading.classList.add('hidden'), 4500);
  loadEditor();

  function setFullscreenState(active) {
    frameWrap.classList.toggle('is-fullscreen', active);
    if (i18nFullscreen) {
      i18nFullscreen.textContent = active ? dict.exitFullscreen : dict.fullscreen;
    }
  }

  btnFullscreen.addEventListener('click', async () => {
    if (document.fullscreenElement) {
      try { await document.exitFullscreen(); } catch {}
      setFullscreenState(false);
      return;
    }
    if (frameWrap.requestFullscreen) {
      try {
        await frameWrap.requestFullscreen();
        setFullscreenState(true);
        return;
      } catch {}
    }
    setFullscreenState(!frameWrap.classList.contains('is-fullscreen'));
  });

  document.addEventListener('fullscreenchange', () => {
    setFullscreenState(Boolean(document.fullscreenElement));
  });

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && frameWrap.classList.contains('is-fullscreen')) {
      setFullscreenState(false);
    }
  });
